$files = Get-ChildItem $dir -File -Filter '*.md'
$totalReplacements = 0
foreach ($file in $files) {
    $content = Get-Content $file.FullName -Raw
    $originalLength = $content.Length
    foreach ($key in $replacements.Keys) {
        $value = $replacements[$key]
        $count = ([regex]::Matches($content, [regex]::Escape($key))).Count
        if ($count -gt 0) {
            $content = $content.Replace($key, $value)
            $totalReplacements += $count
            Write-Host "  $($file.Name): '$key' -> '$value' ($count occurrences)"
        }
    }
    if ($content -ne (Get-Content $file.FullName -Raw)) {
        [System.IO.File]::WriteAllText($file.FullName, $content, [System.Text.UTF8Encoding]::new($false))
    }
}
Write-Host "`nTotal replacements: $totalReplacements"
